#!/usr/bin/env python3
"""Write `NearCrypto/Bls12381/Isogeny.lean`: the constants of the hash-to-curve maps of blst.

`blst` 0.3.11 (`src/map_to_g1.c`, `src/map_to_g2.c`) keeps them as Montgomery limbs; this reads the
arrays and writes plain integers. Usage:

    gen_bls_isogeny.py BLST_SRC_DIR > NearCrypto/Bls12381/Isogeny.lean

BLST_SRC_DIR is `blst-0.3.11/blst/src` of the cargo registry. The constants are those of RFC 9380
(appendix E.2 and E.3, the 11-isogeny and the 3-isogeny of the SSWU curves); the committed file is
checked by `tools/tests/test_bls_isogeny.py`, which verifies that the maps send points of the
isogenous curves to points of the target curves.
"""

import re
import sys
from pathlib import Path

P = 0x1A0111EA397FE69A4B1BA7B6434BACD764774B84F38512BF6730D2A0F6B0F6241EABFFFEB153FFFFB9FEFFFFFFFFAAAB
RINV = pow(2**384, -1, P)


def group_values(text):
    """The values of the innermost brace groups of `text`, in order, out of Montgomery form."""
    out = []
    for g in re.findall(r"\{([^{}]*)\}", text):
        limbs = [int(x, 16) for x in re.findall(r"TO_LIMB_T\((0x[0-9a-fA-F]+)\)", g)]
        if limbs:
            assert len(limbs) == 6
            out.append(sum(v << (64 * i) for i, v in enumerate(limbs)) * RINV % P)
        else:
            assert g.strip() == "0", g
            out.append(0)
    return out


def array(source, name):
    m = re.search(name + r"\[\]\s*=\s*\{(.*?)\n\s*\};", source, re.S)
    assert m, name
    return group_values(m.group(1))


def scalar(source, name):
    m = re.search(r"static const vec384x? " + name + r"\s*=\s*\{(.*?)\n\s*\};", source, re.S)
    assert m, name
    body = m.group(1)
    return group_values(body if "{" in body else "{" + body + "}")


def emit(name, doc, values):
    """Each value as six 64-bit limbs, least significant first, three to a line."""
    print(f"/-- {doc} -/")
    print(f"def {name} : Array Nat :=")
    print("  limbs")
    rows = []
    for v in values:
        ls = [f"0x{(v >> (64 * i)) & (2**64 - 1):016x}" for i in range(6)]
        rows.append(", ".join(ls[:3]) + ",")
        rows.append(", ".join(ls[3:]) + ",")
    rows[-1] = rows[-1][:-1]
    print("    #[" + "\n      ".join(rows) + "]")
    print()


def main(src):
    s1 = (Path(src) / "map_to_g1.c").read_text()
    s2 = (Path(src) / "map_to_g2.c").read_text()
    print("""/-!
# Constants of the hash-to-curve maps of BLS12-381

Generated by `scripts/gen_bls_isogeny.py` from `blst` 0.3.11 (`map_to_g1.c`, `map_to_g2.c`), which
holds the constants of RFC 9380 (appendix E.2 and E.3). The coefficients of the isogenies are
listed from the constant term; a denominator's leading coefficient `1` is implicit, as in `blst`.
For the curves over `Fp2` an element `c0 + c1 u` is the pair of consecutive entries `c0, c1`.
-/

namespace NearCrypto.Bls12381.Isogeny

/-- The numbers whose 64-bit limbs, six per number, least significant first, are given. -/
def limbs (ls : Array Nat) : Array Nat :=
  (Array.range (ls.size / 6)).map fun i =>
    (List.range 6).foldl (fun acc j => acc ||| ls[6 * i + j]! <<< (64 * j)) 0
""")
    a, b = scalar(s1, "Aprime_E1"), scalar(s1, "Bprime_E1")
    assert len(a) == len(b) == 1
    emit("a1", "`A'` of the curve `y² = x³ + A' x + B'` isogenous to `E1`.", a)
    emit("b1", "`B'`.", b)
    emit("xNum1", "`x = xNum / xDen` of the 11-isogeny: numerator, 12 coefficients.",
         array(s1, "isogeny_map_x_num"))
    emit("xDen1", "Denominator, 10 coefficients below the leading `x¹⁰`.", array(s1, "isogeny_map_x_den"))
    emit("yNum1", "`y = y' yNum / yDen`: numerator, 16 coefficients.", array(s1, "isogeny_map_y_num"))
    emit("yDen1", "Denominator, 15 coefficients below the leading `x¹⁵`.", array(s1, "isogeny_map_y_den"))
    emit("a2", "`A' = 240 u` of `E2`'s isogenous curve (`c0, c1`).", scalar(s2, "Aprime_E2"))
    emit("b2", "`B' = 1012 (1 + u)` (`c0, c1`).", scalar(s2, "Bprime_E2"))
    emit("xNum2", "3-isogeny: numerator, 4 coefficients of `Fp2` (`c0, c1` pairs).",
         array(s2, "isogeny_map_x_num"))
    emit("xDen2", "Denominator, 2 coefficients below the leading `x²`.", array(s2, "isogeny_map_x_den"))
    emit("yNum2", "`y` numerator, 4 coefficients.", array(s2, "isogeny_map_y_num"))
    emit("yDen2", "`y` denominator, 3 coefficients below the leading `x³`.", array(s2, "isogeny_map_y_den"))
    print("end NearCrypto.Bls12381.Isogeny")


if __name__ == "__main__":
    main(sys.argv[1])
