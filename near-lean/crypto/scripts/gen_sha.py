#!/usr/bin/env python3
"""Generate NearCrypto/Sha2Rounds.lean: the unrolled SHA-256 and SHA-512 block functions.

One block is 16 big-endian words, the message schedule is computed on the fly into locals
(`w16 .. w63` or `w79`) and each round is straight-line code on unboxed registers: round `t` only
produces a new `d` and a new `h`, and the names of the eight working variables rotate instead of
moving. The constants are the ones of FIPS 180-4 (the `Spec` derives them from the primes; the
test vectors check both).

Usage: scripts/gen_sha.py > NearCrypto/Sha2Rounds.lean; then `just lean-format` on the file.
"""

K256 = [
    0x428a2f98, 0x71374491, 0xb5c0fbcf, 0xe9b5dba5, 0x3956c25b, 0x59f111f1, 0x923f82a4, 0xab1c5ed5,
    0xd807aa98, 0x12835b01, 0x243185be, 0x550c7dc3, 0x72be5d74, 0x80deb1fe, 0x9bdc06a7, 0xc19bf174,
    0xe49b69c1, 0xefbe4786, 0x0fc19dc6, 0x240ca1cc, 0x2de92c6f, 0x4a7484aa, 0x5cb0a9dc, 0x76f988da,
    0x983e5152, 0xa831c66d, 0xb00327c8, 0xbf597fc7, 0xc6e00bf3, 0xd5a79147, 0x06ca6351, 0x14292967,
    0x27b70a85, 0x2e1b2138, 0x4d2c6dfc, 0x53380d13, 0x650a7354, 0x766a0abb, 0x81c2c92e, 0x92722c85,
    0xa2bfe8a1, 0xa81a664b, 0xc24b8b70, 0xc76c51a3, 0xd192e819, 0xd6990624, 0xf40e3585, 0x106aa070,
    0x19a4c116, 0x1e376c08, 0x2748774c, 0x34b0bcb5, 0x391c0cb3, 0x4ed8aa4a, 0x5b9cca4f, 0x682e6ff3,
    0x748f82ee, 0x78a5636f, 0x84c87814, 0x8cc70208, 0x90befffa, 0xa4506ceb, 0xbef9a3f7, 0xc67178f2]


def primes(n):
    result, k = [], 2
    while len(result) < n:
        if all(k % d for d in range(2, int(k ** 0.5) + 1)):
            result.append(k)
        k += 1
    return result


def iroot(k, n):
    lo, hi = 0, 1 << 400
    while hi - lo > 1:
        mid = (lo + hi) // 2
        if mid ** k <= n:
            lo = mid
        else:
            hi = mid
    return lo


K512 = [iroot(3, p << 192) & (2 ** 64 - 1) for p in primes(80)]

# name, word type, bytes, rounds, round constants, big sigmas, small sigmas, load function
PARAMS = {
    "256": dict(ty="UInt32", bits=32, rounds=64, k=K256, big0=(2, 13, 22), big1=(6, 11, 25),
                s0=(7, 18, 3), s1=(17, 19, 10), load="be32", step=4),
    "512": dict(ty="UInt64", bits=64, rounds=80, k=K512, big0=(28, 34, 39), big1=(14, 18, 41),
                s0=(1, 8, 7), s1=(19, 61, 6), load="be64", step=8),
}


def lean_hex(value, bits):
    return "0x%0*x" % (bits // 4, value)


def generate(name):
    p = PARAMS[name]
    ty, bits = p["ty"], p["bits"]
    rot = f"rotr{name}"
    lines = [f"/-- One SHA-{name} block of `data` at byte offset `off` compressed into `s`. -/",
             f"def compress{name} (s : State{name}) (data : ByteArray) (off : Nat) : State{name} :="]
    for t in range(16):
        lines.append(f"  let w{t} := {p['load']} data (off + {p['step'] * t})")
    for t in range(16, p["rounds"]):
        x, y = f"w{t - 15}", f"w{t - 2}"
        s0 = f"{rot} {x} {p['s0'][0]} ^^^ {rot} {x} {p['s0'][1]} ^^^ {x} >>> {p['s0'][2]}"
        s1 = f"{rot} {y} {p['s1'][0]} ^^^ {rot} {y} {p['s1'][1]} ^^^ {y} >>> {p['s1'][2]}"
        lines.append(f"  let w{t} := w{t - 16} + ({s0}) + w{t - 7} + ({s1})")
    names = ["a", "b", "c", "d", "e", "f", "g", "h"]
    cur = {n: f"s.{n}" for n in names}
    for t in range(p["rounds"]):
        a, b, c, d, e, f, g, h = (cur[n] for n in names)
        big1 = " ^^^ ".join(f"{rot} {e} {n}" for n in p["big1"])
        big0 = " ^^^ ".join(f"{rot} {a} {n}" for n in p["big0"])
        k = lean_hex(p["k"][t], bits)
        lines.append(f"  let t1_{t} := {h} + ({big1}) + (({e} &&& {f}) ^^^ (~~~{e} &&& {g})) + {k} + w{t}")
        lines.append(f"  let t2_{t} := ({big0}) + (({a} &&& {b}) ^^^ ({a} &&& {c}) ^^^ ({b} &&& {c}))")
        lines.append(f"  let d_{t} := {d} + t1_{t}")
        lines.append(f"  let h_{t} := t1_{t} + t2_{t}")
        cur = {"a": f"h_{t}", "b": a, "c": b, "d": c, "e": f"d_{t}", "f": e, "g": f, "h": g}
    out = ", ".join(f"s.{n} + {cur[n]}" for n in names)
    lines.append(f"  ⟨{out}⟩")
    return "\n".join(lines)


