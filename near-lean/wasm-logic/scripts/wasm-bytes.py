#!/usr/bin/env python3
"""Write a .wasm file as a Lean `ByteArray` literal.

The logic's examples reason about modules as the decoder reads them from
their bytes, so the bytes have to be a Lean term the kernel can evaluate.

    scripts/wasm-bytes.py <file.wasm> <Lean.Module.Name> <defName> > <file.lean>

`scripts/check-wasm-bytes.sh` recompiles every example's `.wat` with the
pinned wasm-tools and fails if a committed `.wasm` or its Lean literal is
out of date.
"""

import sys
from pathlib import Path


def main() -> int:
    if len(sys.argv) != 4:
        print(__doc__, file=sys.stderr)
        return 2
    path, namespace, name = Path(sys.argv[1]), sys.argv[2], sys.argv[3]
    data = path.read_bytes()
    lines = []
    for start in range(0, len(data), 16):
        chunk = data[start:start + 16]
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in chunk))
    print(f"/-! Generated by `scripts/wasm-bytes.py` from `{path.name}`; do not edit. -/")
    print()
    print(f"namespace {namespace}")
    print()
    print(f"/-- The bytes of `{path.name}`. -/")
    print(f"def {name} : ByteArray := ⟨#[")
    print(",\n".join(lines))
    print("  ]⟩")
    print()
    print(f"end {namespace}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
