#!/usr/bin/env python3
"""Generate NearCrypto/Ed25519/FeMul.lean: the multiplication and squaring of GF(2^255 - 19).

A field element is ten limbs of alternating 26 and 25 bits (radix 2^25.5, as in ref10 and
curve25519-donna-32bit): limb i has weight 2^ceil(25.5 i). The schoolbook product of limbs i and j
lands at weight i + j, doubled when both are odd (their weights sum to one more than the weight of
i + j), and wraps with a factor 19 past limb 9 (2^255 = 19 mod p). With limbs below 2^27 every
accumulator stays below 2^63, so plain wrapping `UInt64` arithmetic is exact. `Fe.carry` brings
the limbs back to 26 and 25 bits (the first limb is below 2^26, the second may exceed 2^25 by up
to 2^16).

Usage: scripts/gen_fe.py > NearCrypto/Ed25519/FeMul.lean; then `just lean-format` on the file.
"""

def terms(square: bool):
    """For each result limb k, the list of (coefficient, i, j) with a_i * b_j."""
    result = [[] for _ in range(10)]
    for i in range(10):
        for j in range(i if square else 0, 10):
            coefficient = 1
            if i % 2 == 1 and j % 2 == 1:
                coefficient *= 2
            k = i + j
            if k >= 10:
                k -= 10
                coefficient *= 19
            if square and i != j:
                coefficient *= 2
            result[k].append((coefficient, i, j))
    return result


def accumulate(square: bool):
    lines = []
    for k, ts in enumerate(terms(square)):
        parts = []
        for coefficient, i, j in ts:
            x, y = f"a.l{i}", f"a.l{j}" if square else f"b.l{j}"
            body = f"{x} * {y}"
            parts.append(body if coefficient == 1 else f"{coefficient} * ({body})")
        lines.append(f"  let r{k} : UInt64 :=\n    " + " + ".join(parts))
    return "\n".join(lines)


def finish():
    return "  Fe.carry " + " ".join(f"r{k}" for k in range(10))


print("""import NearCrypto.Ed25519.Fe

/-!
# Multiplication and squaring of GF(2²⁵⁵ − 19)

Generated by `scripts/gen_fe.py`; see there for the construction. The inputs have limbs below
2²⁷ and the outputs are reduced (`Fe`).
-/

namespace NearCrypto.Ed25519.Fe

/-- Product. -/
def mul (a b : Fe) : Fe :=""")
print(accumulate(False))
print(finish())
print("""
/-- Square. -/
def sq (a : Fe) : Fe :=""")
print(accumulate(True))
print(finish())
print("\nend NearCrypto.Ed25519.Fe")
