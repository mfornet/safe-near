#!/usr/bin/env python3
"""Generate NearCrypto/Secp256k1/FpMul.lean: the multiplication and squaring of GF(2^256 - 2^32 - 977).

A field element is ten limbs of 26 bits (the last one 22 bits when reduced), limb i of weight 2^(26 i).
The schoolbook product of limbs i and j lands in column i + j, 19 columns in all. With limbs below
2^28 every column stays below 2^61, so plain wrapping `UInt64` arithmetic is exact.

Columns 10 to 18 have weight 2^260 = 16 * 2^256 = 2^36 + 15632 (mod p). They are carried into
26-bit limbs h0 to h8 and a last carry h9, and folded: h_k * 15632 lands in column k and
h_k * 2^10 in column k + 1. What lands at weight 2^260 again (h9 * 2^10) is folded once more:
h9 * 2^10 * 15632 in column 0 and h9 * 2^20 in column 1. `Fp.carry` brings the ten sums back to
reduced limbs.

Usage: scripts/gen_fp.py > NearCrypto/Secp256k1/FpMul.lean; then `just lean-format` on the file.
"""


def columns(square: bool):
    """For each column k, the list of (coefficient, i, j) with a_i * b_j."""
    result = [[] for _ in range(19)]
    for i in range(10):
        for j in range(i if square else 0, 10):
            coefficient = 2 if square and i != j else 1
            result[i + j].append((coefficient, i, j))
    return result


def accumulate(square: bool):
    lines = []
    for k, ts in enumerate(columns(square)):
        parts = []
        for coefficient, i, j in ts:
            y = f"a.l{j}" if square else f"b.l{j}"
            body = f"a.l{i} * {y}"
            parts.append(body if coefficient == 1 else f"{coefficient} * ({body})")
        lines.append(f"  let c{k} : UInt64 :=\n    " + " + ".join(parts))
    return "\n".join(lines)


def fold():
    lines = ["  let x : UInt64 := c10", "  let h0 : UInt64 := x &&& 0x3ffffff", "  let k : UInt64 := x >>> 26"]
    for m in range(1, 9):
        lines += [f"  let x : UInt64 := c{10 + m} + k", f"  let h{m} : UInt64 := x &&& 0x3ffffff",
                  "  let k : UInt64 := x >>> 26"]
    lines.append("  let h9 : UInt64 := k")
    lines.append("  let r0 : UInt64 := c0 + 15632 * h0 + 16007168 * h9")
    lines.append("  let r1 : UInt64 := c1 + 15632 * h1 + 1024 * h0 + 1048576 * h9")
    for m in range(2, 10):
        lines.append(f"  let r{m} : UInt64 := c{m} + 15632 * h{m} + 1024 * h{m - 1}")
    lines.append("  Fp.carry " + " ".join(f"r{k}" for k in range(10)))
    return "\n".join(lines)


print("""import NearCrypto.Secp256k1.Fp

/-!
# Multiplication and squaring of GF(2²⁵⁶ − 2³² − 977)

Generated by `scripts/gen_fp.py`; see there for the construction. The inputs have limbs below
2²⁸ and the outputs are reduced (`Fp`).
-/

namespace NearCrypto.Secp256k1.Fp

/-- Product. -/
def mul (a b : Fp) : Fp :=""")
print(accumulate(False))
print(fold())
print("""
/-- Square. -/
def sq (a : Fp) : Fp :=""")
print(accumulate(True))
print(fold())
print("\nend NearCrypto.Secp256k1.Fp")
